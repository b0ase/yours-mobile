// Regenerates src/mobile/wallet/emojiArt/twemoji.ts from the self-hosted Twemoji SVGs beside it
// (jdecked/twemoji@15.1.0 assets/svg, CC-BY 4.0; see ATTRIBUTION.md). Run: node scripts/twemoji-art.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const dir = resolve(import.meta.dirname, '../src/mobile/wallet/emojiArt/twemoji');
const out = {};
for (const f of readdirSync(dir)
  .filter((n) => n.endsWith('.svg'))
  .sort()) {
  const svg = readFileSync(resolve(dir, f), 'utf8').trim();
  const m = /^<svg[^>]*viewBox="0 0 36 36"[^>]*>([\s\S]*)<\/svg>$/.exec(svg);
  if (!m) throw new Error(`unexpected svg ${f}`);
  out[f.replace('.svg', '')] = m[1];
}
const body =
  '// Generated by scripts/twemoji-art.mjs from ./twemoji/*.svg. Do not edit by hand.\n' +
  '// Twemoji graphics (c) X Corp and other contributors, CC-BY 4.0 (https://creativecommons.org/licenses/by/4.0/).\n' +
  '/** Inner markup of each Twemoji SVG (viewBox 0 0 36 36), by codepoint. */\n' +
  `export const TWEMOJI: Readonly<Record<string, string>> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(resolve(dir, '../twemoji.ts'), body);
console.log(Object.keys(out).length, 'emoji');
