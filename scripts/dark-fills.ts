/** Files outside the media list that use a solid bg-black (a dark UI fill; use a dark hex so the sweep catches it). */
export function strayBgBlack(srcDir: string): string[] {
  return walk(srcDir, [])
    .filter((f) => !BG_BLACK_MEDIA.some((m) => f.endsWith(m)))
    .filter((f) => /(?<![\w-])bg-black(?![\w/-])/.test(readFileSync(f, 'utf8')))
    .map((f) => f.slice(srcDir.length).replace(/^\//, ''));
}

function twSelector(cls: string): string {
  const [, pre, base] = cls.match(/^(?:(hover|active|focus):)?(.*)$/)!;
  const esc = (pre ? `${pre}:` : '') + base;
  return '.' + esc.replace(/([:[\]#/.])/g, '\\$1') + (pre ? `:${pre}` : '');
}

export function renderBlock(fills: string[], classes: string[] = []): string {
  const sel = fills
    .flatMap((c) => [`    [style*='background: rgb(${c})'],`, `    [style*='background-color: rgb(${c})'],`])
    .join('\n')
    .replace(/,$/, '');
  return `${BEGIN}
:root[data-bw-tone='mono']
  :is(
${sel}
  ):not(
    :is(.bg-black\\/50, .bg-black\\/60, .bg-black\\/65, .bg-black\\/70, .bg-black\\/80, .bw-videobg, [data-pool-dark]) *
  ) {
  background: var(--bw-surface) !important;
  color: var(--bw-text) !important;
  border-color: rgb(0 0 0 / 0.18) !important;
}${classes.length ? twBlock(classes) : ''}
${END}`;
}

