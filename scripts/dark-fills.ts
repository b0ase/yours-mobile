/**
 * No dark cards in White (owner, 16 Oct 2026). Every dark hex literal in src/ (inline styles, colour constants) gets
 * a mono-tone sweep selector in themes.css, so a hard-coded dark fill turns into the White surface; dark Tailwind
 * fills (bg-[#17191E], hover:bg-[#1f2128], bg-zinc-900) are swept the same way, and dark stylesheet backgrounds
 * must carry a pack override or a CSS_KEEP reason (uncoveredDarkCss). Gold and Dark
 * packs never match (the block is scoped to data-bw-tone='mono').
 *
 *   bun scripts/dark-fills.ts        rewrites the generated block in src/themes.css
 *   cardPatternsLight.test.ts        fails CI when a new dark hex has no selector
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** Pure black stays black: media letterboxes, video players and the obsidian pool use it on purpose. */
const KEEP = new Set(['0,0,0', '1,1,1']);
const MAX_CHANNEL = 0x50;
export const BEGIN = '/* dark-fills:begin (generated by scripts/dark-fills.ts; do not edit by hand) */';
export const END = '/* dark-fills:end */';

function walk(dir: string, out: string[]): string[] {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(e.name) && !/\.test\.tsx?$/.test(e.name)) out.push(p);
  }
  return out;
}

function toRgb(hex: string): [number, number, number] | null {
  let h = hex.slice(1);
  if (h.length === 3) h = [...h].map((c) => c + c).join('');
  if (h.length !== 6) return null;
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)) as [number, number, number];
}

/** Sorted "r, g, b" strings for every dark opaque hex literal in src/. */
export function darkFills(srcDir: string): string[] {
  const set = new Set<string>();
  for (const f of walk(srcDir, [])) {
    for (const m of readFileSync(f, 'utf8').matchAll(/['"`(\s,:]#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![0-9a-fA-F])/g)) {
      const rgb = toRgb('#' + m[1]);
      if (!rgb || Math.max(...rgb) > MAX_CHANNEL || KEEP.has(rgb.join(','))) continue;
      set.add(rgb.join(', '));
    }
  }
  return [...set].sort();
}

/** Tailwind dark fills: arbitrary dark hex (bg-[#17191E], hover:bg-[#1f2128]) and dark palette steps (bg-zinc-900). */
const TW_RE =
  /(?<![\w-])((?:hover|active|focus):)?(bg-\[#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\]|bg-(?:zinc|neutral|slate|gray|stone)-(?:8|9)\d0|(?:from|via)-(?:black|(?:zinc|neutral|slate|gray|stone)-9\d0))(?![\w/-])/g;

function twDark(cls: string): boolean {
  const hex = cls.match(/#([0-9a-fA-F]+)/);
  if (!hex) return true;
  const rgb = toRgb('#' + hex[1]);
  return !!rgb && Math.max(...rgb) <= MAX_CHANNEL && !KEEP.has(rgb.join(','));
}

/** Sorted dark Tailwind background classes used in src/ (with their hover/active/focus prefix). */
export function darkClasses(srcDir: string): string[] {
  const set = new Set<string>();
  for (const f of walk(srcDir, [])) {
    for (const m of readFileSync(f, 'utf8').matchAll(TW_RE)) if (twDark(m[2])) set.add((m[1] ?? '') + m[2]);
  }
  return [...set].sort();
}

