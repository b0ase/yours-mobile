function darkValue(v: string): boolean {
  const lit = v.replace(/var\(--[\w-]+,[^()]*(?:\([^()]*\)[^()]*)*\)/g, '');
  for (const m of lit.matchAll(/#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![0-9a-fA-F])/g)) {
    const rgb = toRgb('#' + m[1]);
    if (rgb && Math.max(...rgb) <= MAX_CHANNEL) return true;
  }
  for (const m of lit.matchAll(/rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)(?:\s*[,/]\s*([\d.]+))?/g)) {
    if (Math.max(+m[1], +m[2], +m[3]) <= MAX_CHANNEL && (m[4] === undefined || +m[4] >= 0.5)) return true;
  }
  return /(?<![\w-])black(?![\w-])/.test(lit);
}

function cssFiles(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) cssFiles(p, out);
    else if (e.name.endsWith('.css')) out.push(p);
  }
  return out;
}

/** The subject of a selector: its last class (or the whole selector when it has none). */
function subject(sel: string): string {
  const cls = sel.replace(/::?[\w-]+(\([^)]*\))?/g, '').match(/\.[\w-]+/g);
  return cls ? cls[cls.length - 1] : sel.trim();
}

/** Selectors in src/ stylesheets with a dark background and no pack override or CSS_KEEP entry. */
export function uncoveredDarkCss(srcDir: string): string[] {
  const files = cssFiles(srcDir).map((f) => [f, readFileSync(f, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')] as const);
  const themed = files
    .flatMap(([, css]) => [...css.matchAll(/([^{}]+)\{/g)].map((m) => m[1]))
    .filter((p) => p.includes('[data-bw-'))
    .join('\n');
  const out = new Set<string>();
  for (const [f, css] of files) {
    if (f.endsWith('themes.css')) continue;
    for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      if (m[1].includes('[data-bw-')) continue;
      const bg = [...m[2].matchAll(/background(?:-color|-image)?\s*:([^;]+)/g)].map((x) => x[1]).join(' ');
      if (!bg || !darkValue(bg)) continue;
      for (const sel of m[1].split(',').map((x) => x.trim().replace(/\s+/g, ' '))) {
        const subj = subject(sel);
        if (sel.startsWith('@') || CSS_KEEP[subj] || CSS_KEEP[sel] || CSS_KEEP[sel.split(' ').pop()!]) continue;
        if (new RegExp(subj.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?![\\w-])').test(themed)) continue;
        out.add(`${f.slice(srcDir.length).replace(/^\//, '')}: ${sel}`);
      }
    }
  }
  return [...out].sort();
}

const NOT_MEDIA = `:not(
    :is(.bg-black\\/50, .bg-black\\/60, .bg-black\\/65, .bg-black\\/70, .bg-black\\/80, .bw-videobg, [data-pool-dark]) *
  )`;

/** Dark Tailwind fills: the darkest become the white surface; raised greys and hover states take the light tint. */
function twBlock(classes: string[]): string {
  const deep = classes.filter((c) => !/^(hover|active|focus):/.test(c) && !raised(c));
  const soft = classes.filter((c) => !deep.includes(c));
  const rule = (list: string[], bg: string) =>
    list.length
      ? `
:root[data-bw-tone='mono']
  :is(
${list.map((c) => `    ${twSelector(c)}`).join(',\n')}
  )${NOT_MEDIA} {
  background: ${bg} !important;
  color: var(--bw-text) !important;
}`
      : '';
  return rule(deep, 'var(--bw-surface)') + rule(soft, 'var(--bw-tint)');
}

function raised(cls: string): boolean {
  const hex = cls.match(/#([0-9a-fA-F]+)/);
  if (!hex) return /-8\d0$/.test(cls);
  return Math.max(...(toRgb('#' + hex[1]) ?? [0])) > 0x20;
}

